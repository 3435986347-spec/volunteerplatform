-- 奖惩两级审核（协会 2026-09-02 答复问题二）。
--
-- 【为什么改】V32 落地时把审核做成了一级：组织部批完即生效。协会 9/2 答复推翻了这一点：
--   「理事会的同学开单的则自动完成，从下往上反馈的，由组织部的同学审核了，则到理事会审核」
--   「奖励都要理事会审核」「各部门都可以提出奖励申请，理事会审核，理事会发起的奖励，直接审核通过」
--   「理事会没审完，志愿者不会看到处罚」
--
--   合起来是**两级 + 一条快捷通道，且奖与惩不对称**：
--     处罚 · 从下往上   → 组织部初审 → 理事会终审
--     处罚 · 理事会开单 → 开即通过（紧急情况）
--     奖励 · 部门提出   → 理事会终审（**不经组织部**）
--     奖励 · 理事会发起 → 开即通过
--
-- 【为什么占 V40 而不是接着 V39 随便挑一个】V3 那条分支（v3-planning）已经用掉了 V40/V41
--   做积分商城。但 **V2 这条分支要先合进 main**，所以它的迁移号必须更小——否则库先跑到 V42，
--   V3 合进来时 Flyway 会看到 V40 < 当前版本而拒绝执行（outOfOrder 默认关闭，也不该为此打开）。
--   故本文件占 V40，v3-planning 上那两个顺延为 V41/V42。
--   ⚠️ 那两个文件**只在临时测试容器里跑过、从未在任何真实环境执行**，且所在分支尚未合并，
--   所以改名是安全的——「迁移只要可能跑过就不能原地改」那条规矩保护的是**已部署**的迁移。
--
-- 【为什么新增两列而不是复用 reviewed_by / review_time】那两列此后专指**终审**。
--   已经是「已通过」的历史行，其 reviewed_by 在新模型下正好就是终审人，语义自洽、不必回填。
--   初审另开两列，是为了让「谁初审的、谁终审的」在同一行上都留得住——
--   合用一列会让终审把初审人覆盖掉，而那正是两级审核要留的痕迹。
--
-- 【不加「是否自动通过」列】它可以推出来：type=处罚 且 first_review_by IS NULL 且已通过
--   ⇒ 走的是理事会直接处罚那条快捷通道。奖励本就不经初审，first_review_by 恒为 NULL，
--   不构成歧义。少一列就少一处可能与事实不一致的冗余。
--
-- 【为什么要回填待审的奖励】新模型下奖励不经组织部。存量 review_status=0 的奖励单若不动，
--   会卡在一个「等组织部审」的状态里，而按新规矩组织部根本不该审它——
--   那张单会成为谁也处理不掉的待办。回填把它们直接推到「待终审」。
--   （第 5 批尚未合入 main，真实环境不存在这类行；回填是为了开发/测试库的一致性。）
--
-- 【本文件三条语句都不涉及版本相关特性】ALTER + INSERT + UPDATE 均为普通语句，
--   与 V28（3 张 CREATE + 1 条 INSERT）、V32（ALTER + 2 CREATE + INSERT）同一形态。
--   「一个迁移文件只放一条有失败可能的语句」那条针对的是 V33/V34 那种版本相关特性
--   （CHECK 要 8.0.16+、utf8mb4_0900_bin 要 8.0.17+），本文件不涉及。

ALTER TABLE honor_reward_punish
    ADD COLUMN first_review_by   BIGINT   DEFAULT NULL COMMENT '初审人（组织部）admin_user.id；奖励与理事会直接开单恒为 NULL',
    ADD COLUMN first_review_time DATETIME DEFAULT NULL COMMENT '初审时间';

-- 理事会终审权。与 honor:reward-punish（开单 + 初审）分开：
-- 【它同时是「快捷通道」的判据】开单人持有本点 ⇒ 视为理事会开单 ⇒ 开即通过。
-- 所以授予本点等于同时授予「免审开单」的能力，授权时要当成一件事看。
INSERT INTO permission (code, name, module, type, sort, create_time, is_deleted) VALUES
('honor:reward-punish-final', '奖惩理事会终审', 'honor', 3, 55, NOW(), 0);

-- 存量待审的**奖励**直接推到「待终审」（3）：新模型下它们不经组织部。
-- 处罚保持 0 不动——从下往上的处罚本就该先由组织部初审。
UPDATE honor_reward_punish SET review_status = 3 WHERE review_status = 0 AND type = 1;
