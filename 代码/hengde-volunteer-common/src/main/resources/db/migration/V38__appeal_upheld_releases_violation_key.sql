-- 申诉成立的处罚单不再占住「一条违规最多一张单」的位置（协会 2026-08-11 裁决）。
--
-- 【需求出处】协会 2026-08-11 答复第 8 条，原文：
--     「处罚单被驳回或申诉成立后：用户申诉成立但觉得不惩罚不行，则可以给他开第二张轻一点的处罚单」
--   ——这一句同时答掉了《协会待确认清单》第 9 条（驳回后可否重开，V35 已按「可以」实现）
--   与第 9-附 条（申诉成立后可否重开）。
--
-- 【本条推翻的是什么】V35 只把「已驳回」排除在占位之外，并**刻意**让申诉成立的单继续占位。
--   当时给的理由是：驳回 = 这张单没有成立过（开单环节失误，该允许改正重提）；
--   申诉成立 = 这张单成立过又被推翻（就同一件事再罚一次等于二次处罚）。
--   那个理由在制度上讲得通，但它是**我方推论**，V35 抬头也如实标注了「已记入待确认清单第 9-附 条」。
--   协会给的口径不同：申诉成立只说明**这次判罚过重**，事实仍在，可以按更轻的档重开。
--   推论让位于裁决——这正是当初把它标成待确认、而不是当成需求写死的原因。
--
-- 【修法】占位条件再排除一种：一条违规同时最多只有一张
--   「未删除 且 未被驳回 且 申诉未成立」的单。
--   ⚠️ 「第二张必须更轻」**没有**落成数据库约束，也没有落成 Java 校验——
--   轻重跨类别不可比（换一个更贴切的违规类别重开，扣分未必更少，但并非加重），
--   硬拦会挡住合理场景。已作为问题 B 发给协会：由理事会人工把关，开单页展示原单档位供对照。
--   协会若改口要硬拦，加在 RewardPunishService 而不是这里——那是业务规则，不是数据完整性。
--
-- 【为什么 appeal_status <> 2 是安全的】V32 建列时是
--   `appeal_status TINYINT NOT NULL DEFAULT 0`，非空。若它可空，`NULL <> 2` 求值为 NULL、
--   CASE 落到 ELSE，**每一行未申诉的单都会被判为不占位**，唯一键当场失效且毫无征兆。
--
-- 【为什么可以单条 ALTER 改生成列表达式】同 V35：MySQL 8 的 MODIFY COLUMN 支持直接换表达式
--   并重建依赖它的唯一键（已在容器实测）。拆成 DROP KEY / DROP COLUMN / ADD COLUMN / ADD KEY
--   四条就回到了 V33 抬头那个「做了一半、无法重跑」的形态。
--   **一条语句 = 要么全成、要么什么都没发生。**
--
-- 【为什么不会因存量数据失败】同 V35：新表达式只会把更多行映射成 NULL（多个 NULL 互不相同），
--   等价类只拆不合，原本能共存的行改完仍然互不冲突。
ALTER TABLE honor_reward_punish
    MODIFY COLUMN active_violation_id BIGINT GENERATED ALWAYS AS (
        CASE WHEN is_deleted = 0 AND review_status <> 2 AND appeal_status <> 2
             THEN violation_id ELSE NULL END) STORED
        COMMENT '占位键：仅「未删除、未被驳回、申诉未成立」的单占住其来源违规，见 V38';
