-- 「全部限制能力」单列一个权限点（V2 第 5 批评审第 6 轮）。
--
-- 【需求出处】xlsx Row 73：「志愿者使用的前端功能如出现违规行为，可由**该部门负责的同学**
--   限制其使用，包括但不限制于限制其使用指定天数、拒绝其使用本程序。**监察部拥有全部限制能力**」。
--
-- 【缺陷】V32 只建了一个 honor:reward-punish，开单与审核共用；而开单时 sanctionScope 可以随便填，
--   包括最重的 3「拒绝其使用本程序」。于是任何拿到开单权的部门都拥有全部限制能力——
--   Row 73 最后那句话如果人人都成立，它就不成其为一句要求。
--
-- 【修法】把最重的那一档拆出来单独授权：开出 sanction_scope = 3 的单需要额外持有本权限点。
--   ACTIVITY(1) / COMMUNITY(2) 仍在 honor:reward-punish 之内。
--   落点在 AdminRewardPunishController.create（能否开单是授权问题，与业务规则分开），
--   判定抽成静态方法 assertScopeAllowed 以便被用例钉住极性。
--
-- ⚠️ **这只是 Row 73 的一半**：「该部门负责的同学限制其负责的功能」还需要一张
--   「能力域 ↔ 负责部门」的对应表，而两份材料都没有给出这张表（只点名了监察部）。
--   在协会给出映射之前，本迁移只落地能从原文直接读出的那一条：
--   **最重的一档不再随开单权自动获得**。映射问题已记入《协会待确认清单》第 8 条。
--
-- type: 2=功能操作 3=审核类。本点属「操作」——它决定能开出什么，不是一道审核。
