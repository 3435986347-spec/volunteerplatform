-- 给存量榜样的 link_url 归类（V43 加的 link_type 对存量行一律是 0 不跳转）。
--
-- 【为什么必须归类，不能让它们停在 0】：V43 之前榜样只有一个 link_url，小程序拿到就打开。
-- 如果存量行全留在「不跳转」，那些本来点得开的榜样会在小程序上变成不可点——
-- 这是**功能回退**，而且没人会注意到（它不报错，只是少了个入口）。
-- 更糟的是接下来这一步：运营在后台编辑这样一行时，表单按 link_type=0 提交，
-- 后端就会把 link_url 一起清掉，链接**永久丢失**。
--
-- 【分类依据是形态，不是猜测】：
--   以 / 开头        → 1 小程序内部页面。斜杠开头的不可能是 web 地址，这一条没有歧义。
--   以 https:// 开头 → 2 网页（WebView）。这正是改造前的既有行为——它们本来就是被打开的。
--   其它非空         → 3 外部链接（仅复制）。含 http:// ——微信业务域名不收 http，
--                      标成 WebView 会在正式版白屏，标成「只能复制」至少是能用的降级。
--   空               → 保持 0 不跳转。
--
-- ⚠️ 2 与 3 的边界确实需要人工复核（一条 https 链接到底该内嵌打开还是只给复制，
-- 取决于它的域名有没有备案，而备案清单不在库里）。这里取「维持现状」的那一侧：
-- 改造前它们都是直接打开的，先保持不变，再由运营在后台逐条确认。
UPDATE honor_role_model
SET link_type = CASE
        WHEN link_url IS NULL OR link_url = '' THEN 0
        WHEN link_url LIKE '/%' THEN 1
        WHEN link_url LIKE 'https://%' THEN 2
        ELSE 3
    END
WHERE link_type = 0;
