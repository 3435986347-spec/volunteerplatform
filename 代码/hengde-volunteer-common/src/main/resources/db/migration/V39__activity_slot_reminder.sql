-- 活动开始提醒：给场次记一个「已提醒」的时刻，防止定时任务重复发短信。
--
-- 【需求出处】协会 2026-08-11 报备的通知类模板 `activity-start-reminder`
--   （正文形如「您报名的[活动名]将于[开始时间]开始，地点：[地点]，请携带证件准时签到。」）
--   ——模板早就有了，但没有任何业务事件在调它，因为「活动快开始了」不是某个人点出来的动作，
--   只能由定时任务扫出来。扫就必然要回答一个问题：这一场提醒过了没有。
--
-- ⚠️ 【别在迁移脚本里写美元花括号占位符，注释里也不行】Flyway 会对整个文件做占位符替换，
--   注释一视同仁。把模板原文抄进来会让迁移在解析阶段就报
--   `No value provided for placeholder`，整个应用起不来——包括所有模块的测试。
--   本文件第一版就是这么写的，被 SmsNotifyServiceTest 当场撞出来。故此处一律改用方括号示意。
--
-- 【为什么记在场次上，不是活动上】场次是参与的最小单元（见 V2规划〇甲）。
--   一个活动上午场、下午场各一批人，提醒必须各发各的；记在活动上会让下午场的人收不到，
--   或者上午场的人在前一天就收到写着下午时间的短信。
--
-- 【为什么落库而不是放 Redis】Redis 被清一次，全部历史场次会在下一轮扫描里
--   被判成「没提醒过」而重新群发一遍——那是真金白银的短信费，而且收信人会以为活动又要办一次。
--   这一列是幂等的唯一依据，必须和业务数据同生共死。
--
-- 【为什么可空、不给默认值】NULL 就是「还没提醒过」。给个默认时间反而要靠一个哨兵值去表达空，
--   而存量场次（迁移之前建的）本来就没提醒过，NULL 正确表达了这件事。
--   ⚠️ 由此带来的一个后果写在这里：迁移上线时，所有【尚未开始且落在提醒窗口内】的存量场次
--   会在定时任务第一次跑到时发出提醒。这是对的——那些人本来就该收到；
--   而更早的场次早已过了窗口，扫不到。
ALTER TABLE activity_slot
    ADD COLUMN reminder_sent_time DATETIME NULL COMMENT '开始提醒短信的发出时刻；NULL=尚未提醒';

-- 扫描条件是 `reminder_sent_time IS NULL AND start_time BETWEEN ? AND ?`，
-- 而 activity_slot 原有索引的前导列是 activity_id，这个查询一列都吃不到，只能全表扫。
-- 前导列取 reminder_sent_time：它把「已提醒」的绝大多数行（历史场次会越积越多）直接挡在扫描之外，
-- 再按 start_time 在剩下的一小段里做区间过滤。
-- 【这与 V25、V31 记过的是同一课】加时间/新维度过滤前，先看一眼现有索引的前导列。
CREATE INDEX idx_reminder_pending ON activity_slot (reminder_sent_time, start_time);
